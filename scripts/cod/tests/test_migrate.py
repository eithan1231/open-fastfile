"""`migrate`: bringing the worlds on disk up to date with a DSL change.

The point of these is that a migration needs no game files and is safe to run
twice — it reads the world's own committed `export_metadata.json` and rewrites one
line, so running it again must be a no-op rather than a second line.
"""

import json

import pytest

from scripts.cod.migrate import game_of, migrate_world_game, object_modes, object_modes_world, world_dirs
from scripts.cod.worldfile import ensure_world_game

WORLD = """// mp_x — Modern Warfare 3, imported from the game's own fastfile.

world {
  name: "X (MW3)"
  description: "a map"
  category: "MW3 Multiplayer"
  sky: #b9c6d4
}

include "props.world"
"""


def make_world(root, slug, game="iw5", world_text=WORLD, metadata=True):
    d = root / slug
    d.mkdir()
    (d / "world.world").write_text(world_text)
    if metadata:
        (d / "export_metadata.json").write_text(json.dumps({"map": "mp_x", "game": game}))
    return d


def test_ensure_world_game_adds_after_category(tmp_path):
    d = make_world(tmp_path, "x-mw3")
    assert ensure_world_game(str(d), "iw5") is True
    text = (d / "world.world").read_text()
    # A bare word, as every other enum in the DSL is written, and directly after
    # `category:` — where a full export puts it.
    assert '  category: "MW3 Multiplayer"\n  game: iw5\n' in text


def test_ensure_world_game_is_idempotent(tmp_path):
    d = make_world(tmp_path, "x-mw3")
    ensure_world_game(str(d), "iw5")
    once = (d / "world.world").read_text()
    assert ensure_world_game(str(d), "iw5") is False
    assert (d / "world.world").read_text() == once


def test_ensure_world_game_refuses_a_world_with_no_category(tmp_path):
    d = make_world(tmp_path, "hand-made", world_text='world {\n  name: "H"\n}\n')
    with pytest.raises(SystemExit):
        ensure_world_game(str(d), "iw5")


def test_world_dirs_skips_a_folder_with_no_world_file(tmp_path):
    make_world(tmp_path, "b-mw3")
    make_world(tmp_path, "a-mw2", game="iw4")
    (tmp_path / "catalog").mkdir()
    (tmp_path / "catalog" / "index.json").write_text("{}")
    assert [d.rsplit("/", 1)[-1] for d in world_dirs(str(tmp_path))] == ["a-mw2", "b-mw3"]


def test_game_of_reads_the_committed_metadata(tmp_path):
    d = make_world(tmp_path, "x-ghosts", game="iw6")
    assert game_of(str(d)) == "iw6"


def test_migrate_leaves_a_hand_written_world_alone(tmp_path):
    # No export_metadata.json: nothing knows which game it is, and `game:` is
    # optional for exactly that reason.
    make_world(tmp_path, "handmade", metadata=False)
    make_world(tmp_path, "x-mw3")
    changed, already, skipped = migrate_world_game(str(tmp_path))
    assert changed == ["x-mw3"]
    assert already == []
    assert skipped == ["handmade"]


def test_migrate_dry_run_writes_nothing(tmp_path):
    d = make_world(tmp_path, "x-mw3")
    before = (d / "world.world").read_text()
    changed, already, _ = migrate_world_game(str(tmp_path), dry_run=True)
    assert changed == ["x-mw3"] and already == []
    assert (d / "world.world").read_text() == before


PROPS = """// GENERATED by `python3 -m scripts.cod export`: do not edit by hand.
//
// 3 model placements over 2 assets.

asset com_bomb_objective { catalog: "props/iw5/com_bomb_objective_lod0", source: "com_bomb_objective_lod0.glb" }
asset mv_crate { source: "assets/props/mv/crate_lod0.glb", hull: 0 }

group {
  model { asset: com_bomb_objective, at: 30.394 -10.125 2.501, rotate: 0.0, size: 1.30 1.43 2.08, collide: false }
  model { asset: com_bomb_objective, at: 30.394 -10.125 2.501, rotate: 0.0, size: 1.30 1.43 2.08, collide: false }
}
group {
  model { asset: mv_crate, at: 1.000 2.000 3.000, rotate: 0.0, size: 1.00 1.00 1.00, collide: hull }
}
"""


def props_world(tmp_path):
    d = make_world(tmp_path, "x-mw3")
    (d / "props.world").write_text(PROPS)
    bomb = {"classname": "script_model", "model": "com_bomb_objective", "at": [30.3942, -10.1249, 2.501]}
    entities = [
        {**bomb, "script_gameobjectname": "bombzone"},
        {**bomb, "script_gameobjectname": "dd_bombzone"},
        {"classname": "script_model", "model": "mv/crate", "at": [1.0, 2.0, 3.0], "script_gameobjectname": "hq"},
        {"classname": "script_model", "model": "com_bomb_objective", "at": [9, 9, 9], "script_gameobjectname": "sab"},
    ]
    (d / "export_metadata.json").write_text(json.dumps({"map": "mp_x", "game": "iw5", "entities": entities}))
    return d


def test_object_modes_tags_each_placement_by_its_entity_and_is_idempotent(tmp_path):
    d = props_world(tmp_path)
    assert object_modes_world(str(d)) == (3, 4, 1)  # three lines and the header; the `sab` crate has no placement
    text = (d / "props.world").read_text()
    # Two entities share a spot: each line takes its own, in the lump's order.
    assert text.index('collide: false, mode: "sd" }') < text.index('collide: false, mode: "dd" }')
    assert 'collide: hull, mode: "koth" }' in text
    assert "// 3 model placements over 2 assets.\n// 3 exist only in the game modes their `mode:` names.\n\n" in text

    assert object_modes_world(str(d)) == (3, 0, 1)
    assert (d / "props.world").read_text() == text


def test_object_modes_dry_run_writes_nothing(tmp_path):
    d = props_world(tmp_path)
    assert object_modes(str(tmp_path), dry_run=True) == [("x-mw3", 3, 4, 1)]
    assert (d / "props.world").read_text() == PROPS


def test_object_modes_tells_two_crates_at_one_spot_apart_by_how_they_are_turned(tmp_path):
    # mp_afghan and mp_terminal: an everyday crate and a bomb site's, one spot, two yaws.
    d = make_world(tmp_path, "x-mw2", game="iw4")
    crate = "  model { asset: com_bomb_objective, at: 1.000 2.000 3.000, rotate: %s, size: 1.00 1.00 1.00, collide: false }"
    (d / "props.world").write_text(PROPS.split("group {")[0] + "group {\n" + crate % "90.0" + "\n" + crate % "270.0" + "\n}\n")
    here = {"classname": "script_model", "model": "com_bomb_objective", "at": [1.0, 2.0, 3.0]}
    entities = [{**here, "angles": "0 270 0"}, {**here, "angles": "0 90 0", "script_gameobjectname": "bombzone"}]
    (d / "export_metadata.json").write_text(json.dumps({"map": "mp_x", "game": "iw4", "entities": entities}))
    assert object_modes_world(str(d))[0] == 1
    assert 'rotate: 90.0, size: 1.00 1.00 1.00, collide: false, mode: "dd" "sd" }' in (d / "props.world").read_text()
