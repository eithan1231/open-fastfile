def test_traversals_are_read_by_animscript_and_skip_other_scripts(tmp_path):
    folder = tmp_path / "animscripts" / "traverse"
    folder.mkdir(parents=True)
    (folder / "zombie_jump_down_190.gsc").write_text(JUMP_DOWN_190)
    (folder / "zombie_mantle_over_40.gsc").write_text(JUMP_DOWN_190)
    (folder / "zombie_shared.gsc").write_text("init_traverse() { }")
    assert actors.read_traversals(str(tmp_path)) == {"zombie_jump_down_190": "ai_zombie_jump_down_190"}


def test_a_root_path_is_metres_from_the_start_key_by_key():
    clip = XAnim("jump", 30, 30.0, False)
    clip.has_root_motion = True
    clip.delta_translation = Track([0, 15, 30], [[10, 0, 5], [49.37, 0, 5], [49.37, 0, -73.74]])
    assert actors.root_path(clip) == [
        [0.0, 0.0, 0.0, 0.0],
        [0.5, pytest.approx(1.0), 0.0, 0.0],
        [1.0, pytest.approx(1.0), 0.0, pytest.approx(-2.0)],
    ]
    assert actors.root_path(XAnim("idle", 30, 30.0, True)) is None


def test_a_clip_set_carries_its_traversals_and_only_their_clips_carry_a_path():
    jump = XAnim("j", 30, 30.0, False)
    jump.has_root_motion, jump.delta_translation = True, Track([0, 30], [[0, 0, 0], [0, 0, -39.37]])
    clips = {"j": jump, "i": XAnim("i", 30, 30.0, True)}
    entry = actors.clip_set_entry("zombie", {"idle": ["i"]}, clips, 96, {"zombie_jump_down_40": "j"})
    assert entry["traversals"] == {"zombie_jump_down_40": "j"}
    assert entry["clipTable"]["j"]["rootPath"][-1] == [1.0, 0.0, 0.0, pytest.approx(-1.0)]
    assert "rootPath" not in entry["clipTable"]["i"]


