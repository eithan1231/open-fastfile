def test_an_alias_list_keeps_its_repeats_because_a_repeat_is_a_weight():
    assert actors.alias_models(BODIES) == ["c_ger_honorguard_body1"] + ["c_ger_honorguard_body2"] * 3


def test_a_character_names_its_body_and_head_lists_and_its_gibs():
    character = actors.read_character(CHARACTER)
    assert character["body"] == ("alias", "c_ger_honorguard_zomb_bodyalias")
    assert character["head"] == ("alias", "c_ger_honorguard_zomb_headalias")
    # A gib is a model or a list to pick from; `gibSpawnTag1` is a joint, not a gib.
    assert character["gibs"] == {
        "torsoDmg1": ("model", "char_ger_honorgd_body1_g_upclean"),
        "torsoDmg2": ("alias", "char_ger_hnrgrd_body1_g_rarmoffalias"),
    }


def test_a_character_with_one_model_and_no_head_is_read_too():
    assert actors.read_character(DOG) == {"body": ("model", "zombie_wolf"), "head": None, "gibs": {}}


def test_an_aitype_gives_its_health_size_and_characters():
    ai = actors.read_aitype(AITYPE)
    assert ai == {"characters": ["c_ger_honorguard_zt"], "health": 150, "bounds": ((-16, -16, 0), (16, 16, 72))}
    # A `switch` over characters names one per case: the weight get_random_character gives it.
    assert actors.read_aitype(DOG_AITYPE)["characters"] == ["character_sp_zombie_dog"] * 2


def test_read_cast_follows_aitype_to_character_to_alias_lists(tmp_path):
    cast = actors.read_cast(_raw(tmp_path), "zombie_ger_zombie")
    assert cast["bodies"] == [("c_ger_honorguard_body1", 1), ("c_ger_honorguard_body2", 3)]
    assert cast["heads"] == [("c_ger_zombie_head1", 1), ("c_ger_zombie_head2", 1)]
    assert cast["gibs"]["torsoDmg2"] == ["char_ger_honorgd_body1_g_rarmoff_1", "char_ger_honorgd_body1_g_rarmoff_2"]
    dog = actors.read_cast(str(tmp_path), "zombie_dog")
    assert dog["bodies"] == [("zombie_wolf", 2)] and dog["heads"] == []


# -- The role table ---------------------------------------------------------------------


def test_roles_come_out_of_the_games_tables_in_its_order_without_dead_lines():
    roles = actors.resolve_roles(ROLES, actors.anim_tables([ZOMBIEMODE], "zombie"))
    assert roles == {
        "idle": ["ai_zombie_idle_v1_delta"],
        "walk": ["ai_zombie_walk_v1", "ai_zombie_walk_v7", "ai_zombie_walk_v9"],
        "attack": ["ai_zombie_attack_v2", "ai_zombie_attack_v4"],
        # GSC is case-blind and the zone's clip names are lower case.
        "rise": ["ai_zombie_traverse_ground_v1_walk", "ai_zombie_traverse_ground_v2_walk_alta"],
        "riseRun": ["ai_zombie_traverse_ground_v1_run"],
    }


def test_a_maps_own_script_replaces_one_variant_in_place():
    base = actors.resolve_roles(ROLES, actors.anim_tables([ZOMBIEMODE], "zombie"))
    theater = actors.resolve_roles(ROLES, actors.anim_tables([ZOMBIEMODE, THEATER], "zombie"))
    assert theater["walk"] == ["ai_zombie_walk_v1", "ai_zombie_walk_v7", "ai_zombie_walk_v8"]
    assert {r for r in ROLES if theater[r] != base[r]} == {"walk"}


def test_a_role_that_names_nothing_stops_the_build():
    with pytest.raises(ValueError, match="walk9"):
        actors.resolve_roles({"walk": ("scr_anim.walk9",)}, actors.anim_tables([ZOMBIEMODE], "zombie"))


def test_the_zombie_table_indexes_what_the_spawner_picks_among():
    # `randomintrange(1, 8)` / `(1, 6)` / `(1, 4)`: the upper bound is exclusive.
    assert actors.ZOMBIE_CLIP_ROLES["walk"][-1] == "scr_anim.walk7"
    assert actors.ZOMBIE_CLIP_ROLES["run"][-1] == "scr_anim.run5"
    assert actors.ZOMBIE_CLIP_ROLES["sprint"][-1] == "scr_anim.sprint3"
    assert set(actors.ONCE_ROLES) <= set(actors.ZOMBIE_CLIP_ROLES)


# -- Root motion --------------------------------------------------------------------------


def test_root_motion_is_metres_per_cycle_in_the_actors_own_frame():
    anim = decode(encode(delta_clip(19)), "walk")
    motion = actors.root_motion(anim)
    assert motion["forward"] == pytest.approx(100 / UNITS_PER_M, abs=1e-4)
    assert motion["left"] == pytest.approx(10 / UNITS_PER_M, abs=1e-4)
    assert motion["yaw"] == pytest.approx(90.0, abs=0.01)
    assert motion["speed"] == pytest.approx(math.hypot(100, 10) / UNITS_PER_M / (4 / 30), rel=1e-3)
    assert actors.root_motion(XAnim("idle", 59, 30.0, True)) is None


def test_a_clip_entry_says_how_long_whether_it_loops_and_when_its_cues_fire():
    clip = XAnim("attack", 54, 30.0, False, notetracks=[("fire", 25)])
    clip.has_root_motion, clip.delta_translation = True, Track([0, 54], [[0, 0, 0], [39.37, 0, 0]])
    entry = actors.clip_entry(clip)
    assert entry["duration"] == pytest.approx(1.8) and entry["looped"] is False
    assert entry["notes"] == [["fire", pytest.approx(25 / 30, abs=1e-4)]]
    assert entry["rootMotion"]["forward"] == pytest.approx(1.0)


# -- The entries ---------------------------------------------------------------------------


def _cast(bodies, heads):
    return {
        "characters": ["c"],
        "bodies": bodies,
        "heads": heads,
        "gibs": {},
        "health": 150,
        "bounds": ((-16, -16, 0), (16, 16, 72)),
    }


def test_an_actor_entry_weights_only_what_is_not_uniform():
    source = actors.ACTORS[0]
    entry = actors.actor_entry(source, _cast([("b1", 1), ("b2", 3)], [("h1", 1), ("h2", 1)]), {})
    assert entry["bodies"] == ["b1.glb", "b2.glb"] and entry["bodyWeights"] == [1, 3]
    assert entry["heads"] == ["h1.glb", "h2.glb"] and "headWeights" not in entry
    assert "roles" not in entry
    assert entry["animations"] == "zombie" and entry["hitboxes"] == "zombie_ger.hitboxes.json"
    assert entry["size"] == {
        "radius": pytest.approx(16 / UNITS_PER_M, abs=1e-4),
        "height": pytest.approx(72 / UNITS_PER_M, abs=1e-4),
    }


def test_an_actor_carries_only_the_roles_its_map_changes():
    entry = actors.actor_entry(actors.ACTORS[0], _cast([("b", 1)], []), {"walk": ["v1", "v8"]})
    assert entry["roles"] == {"walk": ["v1", "v8"]}


def test_a_clip_set_entry_is_found_by_anim_type_and_lists_its_once_roles():
    clips = {"a": XAnim("a", 30, 30.0, False), "i": XAnim("i", 30, 30.0, True)}
    entry = actors.clip_set_entry("zombie", {"idle": ["i"], "attack": ["a"]}, clips, 96)
    assert (entry["id"], entry["animType"], entry["clips"], entry["joints"]) == ("zombie", "zombie", "animations.glb", 96)
    assert entry["onceRoles"] == ["attack"]
    assert set(entry["clipTable"]) == {"a", "i"}


