def _raw(tmp_path):
    for rel, text in {
        "aitype/zombie_ger_zombie.gsc": AITYPE,
        "character/c_ger_honorguard_zt.gsc": CHARACTER,
        "xmodelalias/c_ger_honorguard_zomb_bodyalias.gsc": BODIES,
        "xmodelalias/c_ger_honorguard_zomb_headalias.gsc": HEADS,
        "xmodelalias/char_ger_hnrgrd_body1_g_rarmoffalias.gsc": RARMOFF,
        "aitype/zombie_dog.gsc": DOG_AITYPE,
        "character/character_sp_zombie_dog.gsc": DOG,
    }.items():
        path = tmp_path / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return str(tmp_path)


