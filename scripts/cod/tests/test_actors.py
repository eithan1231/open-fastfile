def test_a_companion_material_gets_its_colour_map_once_per_image(tmp_path):
    mats = tmp_path / "mc"
    mats.mkdir()
    table = {"textures": [{"semantic": "normalMap", "image": "n"}, {"semantic": "colorMap", "image": "body_c"}]}
    for name in ("linen", "lthr"):
        (mats / f"mtl_{name}.json").write_text(json.dumps(table))
    gltf = {
        "materials": [
            {"name": "mc/mtl_head", "pbrMetallicRoughness": {"baseColorTexture": {"index": 0}}},
            {"name": "mc/mtl_linen"},
            {"name": "mc/mtl_lthr"},
            {"name": "mc/mtl_unknown"},
        ],
        "images": [{"uri": "../images/head_c.dds"}],
        "textures": [{"source": 0}],
    }
    assert actors.fill_colour_maps(gltf, str(tmp_path)) == ["mc/mtl_linen", "mc/mtl_lthr"]
    assert gltf["images"] == [{"uri": "../images/head_c.dds"}, {"uri": "../images/body_c.dds"}]
    assert [m.get("pbrMetallicRoughness", {}).get("baseColorTexture") for m in gltf["materials"]] == [
        {"index": 0},
        {"index": 1},
        {"index": 1},
        None,
    ]


